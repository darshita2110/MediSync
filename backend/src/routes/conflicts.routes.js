const express = require('express');
const { requireAuth } = require('../middleware/auth.middleware');
const { requirePatientAccess, manageMedicines, readMedicalRecords } = require('../middleware/access.middleware');
const { registerIds } = require('../utils/validation');
const c = require('../controllers/conflicts.controller');
const router = express.Router();
registerIds(router, ['patientId', 'conflictId']);
const access = [requireAuth, requirePatientAccess];
router.post('/patients/:patientId/conflicts/check', ...access, manageMedicines, c.runCheck);
router.get('/patients/:patientId/conflicts', ...access, readMedicalRecords, c.listConflicts);
router.patch('/patients/:patientId/conflicts/:conflictId', ...access, manageMedicines, c.updateConflict);
module.exports = router;
