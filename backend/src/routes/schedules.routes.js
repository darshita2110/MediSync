const express = require('express');
const { requireAuth } = require('../middleware/auth.middleware');
const { requirePatientAccess, manageMedicines, confirmDoses } = require('../middleware/access.middleware');
const { registerIds } = require('../utils/validation');
const c = require('../controllers/schedules.controller');
const router = express.Router();
registerIds(router, ['patientId', 'itemId', 'doseId', 'scheduleId']);
const access = [requireAuth, requirePatientAccess];
router.post('/patients/:patientId/items/:itemId/schedules', ...access, manageMedicines, c.createSchedule);
router.get('/patients/:patientId/schedules', ...access, c.listSchedules);
router.patch('/patients/:patientId/schedules/:scheduleId', ...access, manageMedicines, c.deactivateSchedule);
router.post('/patients/:patientId/doses/generate', ...access, manageMedicines, c.generateDoses);
router.get('/patients/:patientId/doses', ...access, c.listDoses);
router.patch('/patients/:patientId/doses/:doseId', ...access, confirmDoses, c.confirmDose);
module.exports = router;
