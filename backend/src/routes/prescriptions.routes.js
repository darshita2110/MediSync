const express = require('express');
const { requireAuth } = require('../middleware/auth.middleware');
const { requirePatientAccess, manageMedicines, readMedicalRecords } = require('../middleware/access.middleware');
const { registerIds } = require('../utils/validation');
const c = require('../controllers/prescriptions.controller');
const router = express.Router();
registerIds(router, ['patientId', 'itemId']);
const read = [requireAuth, requirePatientAccess, readMedicalRecords];
const write = [requireAuth, requirePatientAccess, manageMedicines];
router.post('/patients/:patientId/prescribers', ...write, c.addPrescriber);
router.get('/patients/:patientId/prescribers', ...read, c.listPrescribers);
router.post('/patients/:patientId/prescriptions', ...write, c.createPrescription);
router.get('/patients/:patientId/prescriptions', ...read, c.listPrescriptions);
router.get('/patients/:patientId/items', ...read, c.listActiveItems);
router.patch('/patients/:patientId/items/:itemId', ...write, c.updateItem);
module.exports = router;
